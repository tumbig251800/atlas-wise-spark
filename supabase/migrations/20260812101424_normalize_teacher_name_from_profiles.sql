-- ============================================================
-- ปัญหา: ครูคนเดียวกันมีชื่อหลายแบบใน classroom_research_suggestions
--   ปวีณา   : "ครูปวีณา แสงสว่าง" / "ปวีณา  แสงสว่าง" (2 ช่องว่าง)
--   รินทราย : "ครูรินทราย สาลีจันทร์" / "น.ส.รินทราย   สาลีจันทร์" (3 ช่องว่าง)
--   พักตร์เพ็ญ: "นางสาวพักตร์เพ็ญ อ้นเก้" / "นางสาวพักตร์เพ็ญ  อนเก้" (ตกไม้เอก)
--   วรกานต์  : "นางสาววรกานต์ ศรีไชยวาล" / "วรกานต์ ศรีไชยวาล"
--   สิรินภา  : "นางสาวสิรินภา จองกลาง" / "สิรินภา จองกลาง"
--   น้ำทิพย์ : "นางสาวน้ำทิพย์ สุขดี" / profiles = "น้ำทิพย์ สุขดี"
--   พัชราภา  : "พัชราภา  เคลือบด้วง" (2 ช่องว่าง)
-- ผู้บริหารยืนยันแล้วว่าเป็นคนเดียวกัน
--
-- ผล: รายงานที่จัดกลุ่มตามชื่อจะแยกครูคนเดียวเป็นหลายบรรทัด
--     และตัวกรอง selected_teachers ใน view (เทียบด้วยชื่อ) อาจกรองไม่ติด
--
-- แก้: sync teacher_name จาก profiles.full_name โดยจับคู่ด้วย teacher_id
--      ไม่ใช้การเทียบชื่อ จึงแม่นยำ 100% ไม่มีโอกาสจับคู่ผิดคน
--      (ทำได้เพราะ migration ก่อนหน้าเติม teacher_id ครบทั้ง 32 แถวแล้ว)
--
-- ไม่แตะ: teacher_id, suggestion_key, status, research_title และเนื้อหาอื่นทั้งหมด
-- ============================================================

UPDATE classroom_research_suggestions c
   SET teacher_name = p.full_name
  FROM profiles p
 WHERE p.user_id = c.teacher_id
   AND c.teacher_name IS DISTINCT FROM p.full_name;
